#include <bits/stdc++.h>
using namespace std;
typedef unsigned long long ull;
typedef long long ll;

// Luke is a Foodie
// https://codeforces.com/problemset/problem/1704/B

int n;
ll x;
ll arr[200005];

void solve() {
    cin >> n >> x;
    for(int i=0; i<n; i++) cin >> arr[i];
}

int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    int tt; 
    cin >> tt;
    while(tt--) solve();
}